/**
 * Lucide-style stroke icon. `flip` mirrors direction-bearing icons (arrows, chevrons)
 * in right-to-left pages so they always point "forward".
 */
export function Icon({ name, className, size = 20, flip }: { name: IconName; className?: string; size?: number; flip?: boolean }) {
  const fill = filled[name];
  const classes = ['icon', flip ? 'flip' : '', className || ''].filter(Boolean).join(' ');
  return (
    <svg
      className={classes}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={fill ? 'currentColor' : 'none'}
      stroke={fill ? 'none' : 'currentColor'}
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {paths[name]}
    </svg>
  );
}

